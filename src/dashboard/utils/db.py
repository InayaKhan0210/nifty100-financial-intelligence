# ---------------------------------------------------------
# Peer Groups
# ---------------------------------------------------------

@st.cache_data(ttl=600)
def get_peers(group_name):
    datasets = _get_datasets()

    df = datasets["peer_groups"].copy()

    possible_columns = [
        "group_name",
        "peer_group",
        "group",
    ]

    group_column = next(
        (
            column
            for column in possible_columns
            if column in df.columns
        ),
        None,
    )

    if group_column is None:
        return pd.DataFrame()

    return df[
        df[group_column].astype(str) == str(group_name)
    ].copy()


# ---------------------------------------------------------
# Valuation
# ---------------------------------------------------------

@st.cache_data(ttl=600)
def get_valuation(ticker):
    """
    Load valuation summary generated by the valuation module.
    """

    path = Path("output/valuation_summary.xlsx")

    if not path.exists():
        return pd.DataFrame()

    df = pd.read_excel(path)

    return df[
        df["company_id"].astype(str) == str(ticker)
    ].copy()