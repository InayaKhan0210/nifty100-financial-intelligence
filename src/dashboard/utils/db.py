from pathlib import Path

import pandas as pd
import streamlit as st

from src.etl.loader import load_core_datasets


# ---------------------------------------------------------
# Load all core datasets once
# ---------------------------------------------------------

@st.cache_data(ttl=600)
def _get_datasets():
    return load_core_datasets()


# ---------------------------------------------------------
# Company data
# ---------------------------------------------------------

@st.cache_data(ttl=600)
def get_companies():
    datasets = _get_datasets()
    return datasets["companies"].copy()


# ---------------------------------------------------------
# Financial ratios
# ---------------------------------------------------------

@st.cache_data(ttl=600)
def get_ratios(ticker, year=None):
    datasets = _get_datasets()

    ratios = datasets["financial_ratios"].copy()

    ratios = ratios[
        ratios["company_id"].astype(str) == str(ticker)
    ].copy()

    # Remove duplicate company-year records
    ratios = ratios.drop_duplicates(
        subset=["company_id", "year"],
        keep="first"
    )

    if year is not None:
        year_str = str(year)

        ratios = ratios[
            ratios["year"].astype(str).str.endswith(year_str)
        ].copy()

    return ratios


